// Content build: content/*.md + SOURCES.md -> src/data/*.json, read.html, works-cited.html.
// Runs automatically with `npm run dev` and `npm run build`, or on its own with `npm run content`.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { alphabetize, parseSources } from './lib/sources.mjs';
import { createParser } from './lib/content.mjs';
import { createPages } from './lib/pages.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/** These must never reach a page. Each one would mean a builder note or raw markdown leaked. */
const FORBIDDEN_ON_PAGES = [
  ['Claude', /Claude/],
  ['raw citation tag', /\[src:/],
  ['raw bold markers', /\*\*/],
  ['pixel-scene note', /Pixel scene/i],
  ['accuracy note', /Accuracy note/i],
  ['student research notes', /Research leads/i],
  ['source status icon', /[✅📄⚠]/u],
];

/** Lists displayed text with no citation, or with text after its last citation, for the student to review. */
function uncitedReport(records) {
  const lines = [
    '# Uncited text report',
    '',
    'Generated by the content build. These are NOT errors. Much of this text is analysis or a summary of',
    'evidence cited nearby. Skim it for facts that should have a citation before you submit.',
    '',
  ];
  const noCite = records.filter((r) => r.cites.length === 0);
  const afterCite = records
    .filter((r) => r.cites.length > 0)
    .map((r) => ({ ...r, tail: r.md.slice(r.md.lastIndexOf('[src:')).replace(/^\[src:[^\]]+\][.,;:]?/, '').trim() }))
    .filter((r) => r.tail.split(/\s+/).length >= 6);
  lines.push(`## Text with no citation (${noCite.length})`, '');
  for (const r of noCite) lines.push(`- **${r.where}:** ${r.md}`);
  lines.push('', `## Text after the last citation (${afterCite.length})`, '');
  for (const r of afterCite) lines.push(`- **${r.where}:** ${r.tail}`);
  return `${lines.join('\n')}\n`;
}

export function buildContent() {
  const read = (path) => readFileSync(join(ROOT, path), 'utf8');
  const write = (path, text) => {
    const full = join(ROOT, path);
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, text);
  };
  const writeJson = (name, value) => write(`src/data/${name}.json`, `${JSON.stringify(value, null, 2)}\n`);

  const sources = parseSources(read('SOURCES.md'));
  const parser = createParser(sources);

  const zones = {
    taproot: parser.parseZone(read('content/02-roots-evolution.md'), 'taproot'),
    'root-india': parser.parseZone(read('content/03-roots-ancient-india.md'), 'root-india'),
    'root-greece': parser.parseZone(read('content/04-roots-ancient-greece.md'), 'root-greece'),
    trunk: parser.parseZone(read('content/05-trunk-modern-history.md'), 'trunk'),
    'branch-1': parser.parseZone(read('content/06-branch-1-body-and-mind.md'), 'branch-1'),
    'branch-2': parser.parseZone(read('content/07-branch-2-ethics-and-earth.md'), 'branch-2'),
    'branch-3': parser.parseZone(read('content/08-branch-3-meat-and-might.md'), 'branch-3'),
  };
  const intro = parser.parseIntro(read('content/01-intro.md'));
  const graft = parser.parseGraft(read('content/09-crossroads-1-vs-2.md'));
  const tangle = parser.parseTangle(read('content/10-crossroads-12-vs-3.md'));
  const canopy = parser.parseCanopy(read('content/11-canopy-conclusion.md'));
  const timeline = parser.parseTimeline(read('content/timeline.md'));
  parser.finish(timeline);

  const sortedSources = alphabetize(sources.values()).map(({ sortKey, ...source }) => source);
  const data = { intro, zones, graft, tangle, canopy, timeline, leaves: parser.leaves, sources: sortedSources };

  writeJson('intro', intro);
  writeJson('zones', zones);
  writeJson('graft', graft);
  writeJson('tangle', tangle);
  writeJson('canopy', canopy);
  writeJson('timeline', timeline);
  writeJson('leaves', parser.leaves);
  writeJson('sources', sortedSources);
  // Ready-made citation chips for the world, which shows sources the content text doesn't tag inline.
  writeJson('chips', Object.fromEntries(sortedSources.map(({ id }) => [id, parser.sourceChip(id)])));
  write('docs/uncited-report.md', uncitedReport(parser.textRecords));

  const pages = createPages({ data, leafChip: parser.sourceChip });
  const output = { 'read.html': pages.readPage(), 'works-cited.html': pages.worksCitedPage() };
  for (const [name, html] of Object.entries(output)) {
    for (const [label, pattern] of FORBIDDEN_ON_PAGES) {
      if (pattern.test(html)) throw new Error(`Content build failed: ${name} contains a ${label}.`);
    }
    write(name, html);
  }
  if (!output['read.html'].includes(parser.leaves.find((l) => l.id === 'trk-p3').supportLine)) {
    throw new Error('Content build failed: read.html is missing the support line on leaf trk-p3.');
  }

  return { leaves: parser.leaves.length, sources: sortedSources.length, timeline: timeline.length };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    const counts = buildContent();
    console.log(`Content built: ${counts.leaves} leaves, ${counts.sources} sources, ${counts.timeline} timeline rows.`);
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
